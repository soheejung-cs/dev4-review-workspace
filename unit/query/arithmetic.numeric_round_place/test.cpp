/* a floating NUMERIC from its text (the value's own digits as precision) */
static DB_VALUE
num (const std::string & s)
{
  DB_VALUE v;
  db_make_null (&v);
  REQUIRE (numeric_coerce_string_to_num (s.c_str (), (int) s.size (), INTL_CODESET_ISO88591, &v) == NO_ERROR);
  return v;
}

/* the value in a fixed NUMERIC (p, s) domain, as a NUMERIC (p, s) column gives it */
static DB_VALUE
fixed (const std::string & s, int p, int sc)
{
  DB_VALUE f = num (s), v;
  unsigned char buf[DB_NUMERIC_BUF_SIZE];
  bool neg = DB_VALUE_NUMERIC_IS_VALUE_NEGATIVE (&f);
  int fp = 0, fs = 0;
  db_get_numeric_precision_and_scale (&f, &fp, &fs, NULL);
  REQUIRE (numeric_coerce_num_to_num (&f, fp, fs, p, sc, buf, &neg) == NO_ERROR);
  db_make_null (&v);
  REQUIRE (db_make_numeric (&v, buf, p, sc, DB_NUMERIC_BUF_SIZE, neg, false) == NO_ERROR);
  return v;
}

static DB_VALUE
value_of (const char *text, int p, int s)
{
  return p < 0 ? num (text) : fixed (text, p, s);
}

static DB_VALUE
place_of (char kind, long long iv, double dv)
{
  DB_VALUE v;
  if (kind == 'i')
    {
      db_make_int (&v, (int) iv);
    }
  else if (kind == 'b')
    {
      db_make_bigint (&v, (DB_BIGINT) iv);
    }
  else
    {
      db_make_double (&v, dv);
    }
  return v;
}

/* what a result is: return code, printed value, precision, scale, sign, fixed or floating */
static std::string
show (int rc, const DB_VALUE & v)
{
  char buf[1024];
  if (DB_IS_NULL (&v))
    {
      return "rc=" + std::to_string (rc) + " NULL";
    }
  if (DB_VALUE_DOMAIN_TYPE (&v) != DB_TYPE_NUMERIC)
    {
      return "rc=" + std::to_string (rc) + " type " + std::to_string (DB_VALUE_DOMAIN_TYPE (&v));
    }
  int p = 0, s = 0;
  bool fl = false;
  db_get_numeric_precision_and_scale (&v, &p, &s, &fl);
  numeric_db_value_print (&v, buf);
  return "rc=" + std::to_string (rc) + " " + buf + " p" + std::to_string (p) + " s" + std::to_string (s)
    + (DB_VALUE_NUMERIC_IS_VALUE_NEGATIVE (&v) ? " neg" : "") + (fl ? " float" : " fixed");
}

static std::string
do_round (DB_VALUE a, DB_VALUE b, bool trunc)
{
  DB_VALUE r;
  db_make_null (&r);
  g_errid = NO_ERROR;
  int rc = trunc ? db_trunc_dbval (&r, &a, &b) : db_round_dbval (&r, &a, &b);
  return show (rc, r);
}

static std::string
do_fc (DB_VALUE a, bool is_floor)
{
  DB_VALUE r;
  db_make_null (&r);
  g_errid = NO_ERROR;
  int rc = is_floor ? db_floor_dbval (&r, &a) : db_ceil_dbval (&r, &a);
  return show (rc, r);
}

