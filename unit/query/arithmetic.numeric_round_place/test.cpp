/*
 * PR#8349 (CBRD-27819) -- ROUND / TRUNC / FLOOR / CEIL of a NUMERIC (src/query/arithmetic.c, server).
 *
 * The PR puts a binary path in front of the decimal-string code of db_round_dbval (), db_trunc_dbval (),
 * db_floor_dbval () and db_ceil_dbval (): numeric_db_value_round_to_place () and numeric_db_value_floor_ceil ()
 * (numeric_opfunc.c) answer when the coefficient is below 2^128 and the scale fits, and say false to leave the rest
 * to the string code. The PR states the results do not change: value, precision, scale, the sign of a zero and the
 * DB_VALUE's form (a fixed NUMERIC returned as it is vs a floating NUMERIC built).
 *
 *   C1  [contract] ROUND / TRUNC at places the decimal string reaches (0 .. scale + 39 cleared digits, a place past
 *       the scale, 1e18, INT64_MAX, DOUBLE fractions): develop's answer, fixed and floating inputs, both signs
 *   C2  [contract] FLOOR / CEIL: the carry that widens the precision (-9.5 -> -10.0 p3), the zero's sign, scales
 *       38 / 39 / 40, the 2^128 neighbourhood (the binary path declines), a value past 2^128
 *   R1a [defect] ROUND to a DOUBLE place past the BIGINT range or NaN (1e19, +Inf, NaN): (DB_BIGINT) d is INT64_MIN
 *       (cvttsd2si), the binary path reads it as a place far left of the point and gives 0; develop keeps the value
 *       (its ptr = end - s + bi2 wraps past end). For 1e19 and +Inf keeping it is the arithmetic answer too.
 *   R1b [defect] ROUND / TRUNC to a place below -2^47 (BIGINT -1e15, -2^62, INT64_MIN; ROUND's DOUBLE -1e19, -Inf):
 *       the binary path gives 0 (the arithmetic answer), develop keeps the value (the same wrap: a user-space stack
 *       address is below 2^47 on x86-64 Linux, so end + (bi2 - s) wraps for every such place) - a change of what
 *       the function answers that the PR does not state.
 *
 * Expected strings of C1 / C2 were taken from 80b84317d (develop, the PR's base) and are the same at 735464f0d.
 * Real code: arithmetic.c (unit under test), numeric_opfunc.c, db_macro.c. Faked: er_set / er_errid / er_clear
 * (the last id), prm_Def (RETURN_NULL_ON_FUNCTION_ERRORS off, ORACLE_COMPAT_NUMBER_BEHAVIOR off), pr_clear_value
 * (db_trunc_dbval () clears its cast holders; the values here own no memory).
 */
